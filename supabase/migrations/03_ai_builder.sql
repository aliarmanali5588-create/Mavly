-- ── Agent runs ──────────────────────────────────────────────────────────────

create table if not exists public.project_runs (
  id uuid primary key default gen_random_uuid(),
  project_id text not null references public.projects (project_id) on delete cascade,
  status text not null default 'init' check (status in ('init', 'done', 'error')),
  model text not null,
  prompt text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  error_message text
);

comment on table public.project_runs is
  'One row per agent invocation. The latest row is the workspace run status.';

create index if not exists project_runs_project_started_idx
  on public.project_runs (project_id, started_at desc);

-- At most one in-flight generation per project. The API also checks this, but
-- two concurrent tabs must not both start a run.
create unique index if not exists project_runs_one_init_per_project
  on public.project_runs (project_id)
  where status = 'init';

