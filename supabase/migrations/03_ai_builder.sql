-- Mavly — AI builder storage
--
-- The builder is no longer a proxy for a hosted service. Projects, generated
-- source files, chat messages and agent runs live in Supabase and are protected
-- by the ownership row in public.projects created by migration 02.
--
-- Everything is additive and idempotent. Authentication, ownership and the
-- existing project id shape are unchanged.

alter table public.projects add column if not exists label text;
alter table public.projects add column if not exists description text not null default '';
alter table public.projects add column if not exists updated_at timestamptz not null default now();

comment on table public.projects is
  'One row per Mavly project owned by one user. project_id is the URL slug.';
comment on column public.projects.label is
  'Optional human-readable project name. project_id remains the identity.';
comment on column public.projects.description is
  'Short project description, usually the first prompt.';

-- The owner may update their own project metadata. They cannot move it to
-- another user: both USING and WITH CHECK require auth.uid() = user_id.
drop policy if exists "projects_update_own" on public.projects;
create policy "projects_update_own"
  on public.projects
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- ── Generated files ─────────────────────────────────────────────────────────

create table if not exists public.project_files (
  project_id text not null references public.projects (project_id) on delete cascade,
  path text not null,
  content text not null,
  updated_at timestamptz not null default now(),
  primary key (project_id, path)
);

comment on table public.project_files is
  'Text source files generated by the Mavly agent. Paths are project-relative.';

create index if not exists project_files_project_id_idx
  on public.project_files (project_id);

alter table public.project_files enable row level security;

drop policy if exists "project_files_select_own" on public.project_files;
create policy "project_files_select_own"
  on public.project_files
  for select
  to authenticated
  using (exists (
    select 1 from public.projects p
    where p.project_id = project_files.project_id
      and p.user_id = (select auth.uid())
  ));

drop policy if exists "project_files_insert_own" on public.project_files;
create policy "project_files_insert_own"
  on public.project_files
  for insert
  to authenticated
  with check (exists (
    select 1 from public.projects p
    where p.project_id = project_files.project_id
      and p.user_id = (select auth.uid())
  ));

drop policy if exists "project_files_update_own" on public.project_files;
create policy "project_files_update_own"
  on public.project_files
  for update
  to authenticated
  using (exists (
    select 1 from public.projects p
    where p.project_id = project_files.project_id
      and p.user_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.projects p
    where p.project_id = project_files.project_id
      and p.user_id = (select auth.uid())
  ));

drop policy if exists "project_files_delete_own" on public.project_files;
create policy "project_files_delete_own"
  on public.project_files
  for delete
  to authenticated
  using (exists (
    select 1 from public.projects p
    where p.project_id = project_files.project_id
      and p.user_id = (select auth.uid())
  ));

-- ── Chat messages ───────────────────────────────────────────────────────────

create table if not exists public.project_messages (
  id uuid primary key default gen_random_uuid(),
  project_id text not null references public.projects (project_id) on delete cascade,
  author text not null check (author in ('user', 'agent')),
  message text not null,
  message_type text not null default 'regular'
    check (message_type in ('regular', 'starting', 'building', 'finished', 'error', 'limit-reached')),
  created_at timestamptz not null default now()
);

